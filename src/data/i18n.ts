export function generateGenderMatchedPeople(count: number, lang: Language): PersonCharacter[] {
  const result: PersonCharacter[] = [];
  const fFaces = [...FEMALE_FACES].sort(() => Math.random() - 0.5);
  const mFaces = [...MALE_FACES].sort(() => Math.random() - 0.5);
  const fNames = [...FEMALE_NAMES[lang]].sort(() => Math.random() - 0.5);
  const mNames = [...MALE_NAMES[lang]].sort(() => Math.random() - 0.5);

  let fCount = 0;
  let mCount = 0;

  for (let i = 0; i < count; i++) {
    const isFemale = Math.random() > 0.5;
    if (isFemale && fCount < fFaces.length && fCount < fNames.length) {
      result.push({ face: fFaces[fCount], name: fNames[fCount], gender: 'female' });
      fCount++;
    } else if (mCount < mFaces.length && mCount < mNames.length) {
      result.push({ face: mFaces[mCount], name: mNames[mCount], gender: 'male' });
      mCount++;
    } else if (fCount < fFaces.length && fCount < fNames.length) {
      result.push({ face: fFaces[fCount], name: fNames[fCount], gender: 'female' });
      fCount++;
    }
  }
  return result.sort(() => Math.random() - 0.5);
}

/**
 * Generates distractor names matching the character's gender
 */
export function getGenderMatchedDistractors(
  targetPerson: PersonCharacter,
  count: number,
  lang: Language,
): string[] {
  const pool =
    targetPerson.gender === "female" ? FEMALE_NAMES[lang] : MALE_NAMES[lang];
  const choices = [targetPerson.name];
  const shuffledPool = [...pool].sort(() => Math.random() - 0.5);

  for (const name of shuffledPool) {
    if (choices.length >= count) break;
    if (!choices.includes(name)) {
      choices.push(name);
    }
  }

  return choices.sort(() => Math.random() - 0.5);
}
